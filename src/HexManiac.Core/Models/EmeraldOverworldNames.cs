      /// <summary>The name of sprite <paramref name="index"/> if the model is an Emerald with the 239 sprites of the unedited game, otherwise null.</summary>
      public static string Name(IDataModel model, int index, int tableLength) {
         if (tableLength != Count || index < 0 || index >= names.Length) return null;
         var code = model.GetGameCode();
         return code.StartsWith("BPEE", StringComparison.Ordinal) ? names[index] : null;
      }
